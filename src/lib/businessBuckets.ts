// Яндекс отдаёт составную категорию через запятую ("Барбершоп,
// парикмахерская", "Кофейня, кафе") — сравниваем каждую часть отдельно и
// берём первую, для которой нашлась корзина (первая часть обычно основная
// специализация точки, остальные — уточнения).
export function bucketForRawCategory(rawCategory: string): string | null {
  const parts = rawCategory.split(',');
  for (const part of parts) {
    const bucket = RAW_CATEGORY_TO_BUCKET[part.trim().toLowerCase()];
    if (bucket) return bucket;
  }
  return null;
}
