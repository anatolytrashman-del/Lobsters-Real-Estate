// Укрупнённые "корзины" бизнеса для location quotient (lib/locationQuotient.ts) —
// владелец: "того же ПВЗ хватит 1 на пару домов, а вот кофеен может быть
// несколько даже в одном доме" — сравнивать по абсолютному числу точек
// разные категории нельзя, у каждой свой "нормальный" уровень насыщения.
// LQ сам это учитывает (делит долю категории в квартале на её долю по
// району), но категория должна быть одна и та же по обе стороны дроби —
// а сырые категории Яндекс.Карт ("Массажный салон", "Косметология",
// "Подология"...) не совпадают друг с другом дословно даже у одной и той
// же ниши. RAW_CATEGORY_TO_BUCKET ниже — единственная точка входа: и
// числитель (квартал), и знаменатель (весь район) в computeLocationQuotients
// берутся из одного и того же датасета (data/districtBusinessCategories.ts
// → district_business_points), просто с разным фильтром по кварталу.
//
// 2026-08-26 — 11 корзин вместо 9: после того как исчерпывающий сбор
// организаций расширился с одного квартала (28 точек) до 17 из 20 (883
// точки, см. журнал docs/session-journal.md), выяснилось, что "Мебель и товары для
// дома" (кухни, двери, сантехника, потолки, шторы — обустройство новых
// квартир) и "Зоотовары и ветеринария" — по размеру сопоставимы с уже
// существующими корзинами (~50 и ~30 упоминаний), но не ложатся ни в одну
// из старых 9 естественно. Остальные новые категории (одежда/обувь,
// электроника, деловые услуги, туризм и т.п.) разложены по старым
// корзинам — см. RAW_CATEGORY_TO_BUCKET ниже.
