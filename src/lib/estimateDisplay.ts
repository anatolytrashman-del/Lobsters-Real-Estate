// Подпись сметы в выпадающих списках "Смета" (Suppliers.tsx, Purchases.tsx).
// Смета без объекта показывается своим названием (title), а владелец называет
// такие сметы со словом "Смета" внутри — "Смета Зелёный" (см. Estimates.tsx).
// Наивное `Смета — ${title}` давало дубль "Смета — Смета Зелёный"
// (владелец, 2026-09-11: "удали дубль слова смета, просто Смета — Зелёный").
// Осторожно: \b в JS работает по ASCII и после кириллицы границу не находит,
// поэтому "не часть другого слова" проверяем через (?![а-яё]) — "Сметана"
// префиксом не считается.
export function estimateOptionLabel(name: string): string {
  const trimmed = name.trim();
  const withoutPrefix = trimmed.replace(/^смета(?![а-яё])[\s—–-]*/i, '').trim();
  return withoutPrefix ? `Смета — ${withoutPrefix}` : 'Смета';
}
