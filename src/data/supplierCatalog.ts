// → КАТЕГОРИЯ (плитка внутри хаба). Владелец, 2026-09-12: «старые „Грильято“ и
// „Ceresit“ не подойдут, категории должны по своей сути поменяться... нравится,
// как организованы визуально категории у ВсеИнструменты, особенно большие
// карточки... максимально понятную структуру — не дробя всё на 1000 мелочей, но
// и сохраняя конкретный профиль».
//
// Структура собрана многоагентным разбором (docs/supplier-catalog.md: сметы Red
// One и Зелёный, снимки 259 сайтов поставщиков, три страницы каталога
// ВсеИнструменты, механика CRM; три независимых проекта → судьи → синтез →
// проверка на прочность). Ось — тип товара, не этап стройки; категория = «одно
// письмо»: слиты только группы, которые у профильных поставщиков реально лежат
// вместе по снимкам сайтов; порог отдельной плитки — ~8 профильных держателей.
//
// Категория связана с базой ДВУМЯ способами:
//   1. по названию — строка supplier_research_requests с таким title — это
//      «домашние» карточки категории (заведены руками или веб-поиском);
//   2. по товарным группам (supplyGroups, справочник supplyCategories.ts) —
//      карточки из ЛЮБОЙ категории, у которых по снимку сайта есть хотя бы одна
//      группа плитки: «по сайту +M». Это и есть ответ на «кто ещё это возит».
// Универсальные поставщики — тип поставщика, а не узел дерева: одна плитка на
// уровне хабов, название строки не меняется никогда (isUniversalRequest).
//
// Каждая из 62 групп справочника лежит ровно в одной категории (проверяется
// тестом ниже по месту использования). Переименования и переезды карточек —
// см. docs/supplier-catalog.md, раздел «Миграция».
import type { SupplierComparisonMode } from './supplierResearch';

export interface SupplierCatalogCategory {
  // Название = title строки supplier_research_requests («домашняя» категория).
  name: string;
  // Что сюда входит — подсказка закупщице на плитке; с перекрёстными «см. …».
  includes: string[];
  // Товарные группы справочника supplyCategories.ts, дословно.
  supplyGroups: string[];
  // Режим сравнения по умолчанию для НОВОЙ закупки в этой категории
  // (сама закупка может переключить): 'lot' — поставка целиком на объект.
  defaultComparisonMode: SupplierComparisonMode;
}

export interface SupplierCatalogHub {
  name: string;
  description: string;
  categories: SupplierCatalogCategory[];
}

