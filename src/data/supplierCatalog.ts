export const SUPPLIER_CATALOG_CATEGORIES: SupplierCatalogCategory[] = SUPPLIER_CATALOG.flatMap((h) => h.categories);

// Старые названия строк категорий закупки → категория каталога. Строки в
// базе переименовываются отдельным SQL (supabase/migrations/
// 20260912-supplier-catalog-rename.sql), а до этого — и если владелец решит
// оставить старое имя — плитка всё равно находит свои «домашние» карточки.
export const LEGACY_REQUEST_TITLES: Record<string, string> = {
  'керамогранит': 'Керамогранит и плитка',
  'ceresit': 'Сухие смеси, грунтовки и гидроизоляция',
  'грильято 100х100': 'Потолки',
  'плинтус': 'Плинтусы, панели и лепнина',
  'краска интерьерная': 'Краски, обои и декоративные покрытия',
  'сантехническое оборудование': 'Сантехника, отопление и бойлеры',
  'умные замки': 'СКУД, видеонаблюдение и слаботочка',
  'умные счётчики': 'Трубы, арматура и счётчики',
  'двери алюминиевые': 'Окна и перегородки',
  'двери деревянные': 'Двери',
};

// Категория по названию строки категории закупки (новому или старому); null —
// строка не из каталога (услуги вроде «ЭДО», свой запрос под смету).
export function findCatalogCategory(requestTitle: string): SupplierCatalogCategory | null {
  const key = requestTitle.trim().toLowerCase();
  const target = (LEGACY_REQUEST_TITLES[key] ?? requestTitle).trim().toLowerCase();
  return SUPPLIER_CATALOG_CATEGORIES.find((c) => c.name.toLowerCase() === target) ?? null;
}

export function catalogHubOf(category: SupplierCatalogCategory): SupplierCatalogHub | null {
  return SUPPLIER_CATALOG.find((h) => h.categories.includes(category)) ?? null;
}
