// Юрлица владельца (ЧУП/ООО/ИП и т.п.) — раздел "Документы" → вкладка
// "Юрлица" (см. Documents.tsx). Каждое юрлицо — отдельная страница
// (LegalEntityDetail.tsx) с несколькими группами документов внутри (первая
// такая группа — налоговые декларации, см. data/taxDeclarations.ts).
//
// Владелец, 2026-09-09: три реальных юрлица — ЧУП «Лавэ Драйв» (Беларусь,
// поставки внутри Беларуси), ИП Трэшмен (Россия, поставки из РФ) и ООО
// «Матрёшка» (новое, отдельная тестовая поставка). Раньше карточка
// организации, автоматически прикрепляемая к первому письму поставщику,
// была ОДНИМ хардкодным файлом на всё приложение (data/organizationCard.ts,
// удалён) — от какого юрлица идёт закупка, нигде не выбиралось, поэтому
// письмо в Россию (например, поставщику Vanguard) всё равно получало
// белорусскую карточку «Лавэ Драйв». Теперь у каждого юрлица — своя
// карточка (cardFile) и она выбирается на уровне категории закупки
// (SupplierRequest.legalEntityId, см. data/supplierResearch.ts) —
// закупщица один раз указывает "это закупки ООО «Матрёшка»", и дальше
// правильная карточка подставляется во все письма этой категории сама.
export interface LegalEntity {
  id: string;
  name: string;
  // Короткое имя для выпадающих списков и email ("ИП Трэшмен",
  // «Лавэ Драйв», "ООО «Матрёшка»") — name может быть длиннее/официальнее
  // (полное наименование), shortName — то, что видит закупщица при выборе
  // юрлица категории. Пусто, пока не заполнено вручную — тогда везде в UI
  // используется name как есть.
  shortName: string;
  // Официальная "Карточка организации" (реквизиты — УНП/адрес/банк/
  // директор), которую нужно приложить к первому письму поставщику этого
  // юрлица. null — карточки ещё нет (новое юрлицо, файл не загружен) —
  // тогда автоматическое вложение просто не добавляется, ничего не
  // выдумываем.
  cardFile: { url: string; fileName: string } | null;
  // Владелец, 2026-09-11: "хочу прикреплять к поставкам вместе с ведомостью
  // материала и карточкой организации ещё инфу по доставке. Для всех
  // поставок ООО Матрёшка нужен документ, где указано: адрес объекта...
  // возможна доставка машинами до 20 тонн с боковой разгрузкой, разгрузка
  // осуществляется нами самостоятельно". Условия у каждого юрлица свои
  // (свой объект, своя разгрузка), поэтому текст живёт здесь, а не в коде:
  // deliveryInfo — то, что владелец печатает на странице юрлица,
  // deliveryFile — сгенерированный из него .docx (lib/deliveryInfoDocx.ts),
  // который и уходит вложением. Файл пересобирается при каждом сохранении
  // текста; пустой deliveryInfo — вложения просто нет (как и с карточкой,
  // ничего не выдумываем).
  deliveryInfo: string;
  deliveryFile: { url: string; fileName: string } | null;
  // Юрлицо по умолчанию — используется для категорий, где закупщица явно
  // не выбрала юрлицо (SupplierRequest.legalEntityId=null), чтобы не ломать
  // уже существующие категории задним числом. Ровно одно юрлицо должно
  // быть отмечено по умолчанию — это не ограничение в БД, а соглашение,
  // соблюдаемое через setLegalEntityDefault (lib/legalEntitiesApi.ts).
  isDefault: boolean;
  // Владелец, 2026-09-09: "если выбираем ИП Трэшмен или Матрешка, страна
  // автоматически Россия; а если ЛАВЭ — Беларусь" — страна, из которой
  // юрлицо реально осуществляет поставки (BulkSendModal подставляет её в
  // выбор страны получателей сразу по выбору юрлица). null — не заполнено
  // (новое юрлицо), автоподстановка тогда просто не срабатывает.
  country: string | null;
  createdAt: string;
}

// Форма строки в таблице Supabase (snake_case-колонки) — см. src/lib/legalEntitiesApi.ts
export interface LegalEntityRow {
  id: string;
  name: string;
  short_name: string | null;
  card_file: { url: string; fileName: string } | null;
  delivery_info: string | null;
  delivery_file: { url: string; fileName: string } | null;
  is_default: boolean;
  country: string | null;
  created_at: string;
}
