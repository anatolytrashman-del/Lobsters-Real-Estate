// Сырые объявления коммерческой недвижимости (Kufar, Realt) — см.
// scripts/sync-kufar-market-offers.mjs, scripts/sync-realt-market-offers.mjs
// и SEO_PLAN.md. Строка — одно объявление, не готовый агрегат: таблица на
// гиде района и страница верификации (/admin/market-offers) считают сводки
// прямо из этих строк, чтобы правки владельца сразу отражались везде.

export interface MarketOffer {
  id: number;
  source: string;
  adId: string;
  dealType: 'sale' | 'rent';
  propertyType: string;
  size: number;
  pricePerSqm: number;
  finishStatus: string;
  // Отдельно от finishStatus: обработал ли владелец эту строку вручную —
  // не только статус отделки, а вообще ("проверил цену/тип/площадь и всё
  // верно" тоже ставит reviewed=true, даже если отделку не трогали).
  // Одновременно это же поле защищает строку от перезаписи при следующем
  // месячном синке (см. scripts/sync-kufar-market-offers.mjs).
  reviewed: boolean;
  // Светлана посмотрела объявление и решила, что оно не подходит (не тот
  // сегмент/дублирует уже отклонённое/явный мусор) — не удаляем строку
  // физически, а помечаем: удалённая строка при следующем месячном синке
  // (тот же ad_id ещё есть у источника) считалась бы "новой" и появлялась
  // бы заново, а reviewed=true уже и так защищает всю строку от
  // перезаписи (см. scripts/sync-kufar-market-offers.mjs) — rejected
  // просто держит её ещё и скрытой из очереди верификации и сводной
  // статистики. Устанавливается вместе с reviewed=true (отклонение —
  // тоже форма обработки).
  rejected: boolean;
  // У Светланы возник вопрос по объявлению (или целой группе дублей —
  // тогда все её карточки получают одинаковый discussionNote и флагуются
  // разом), который нужно обсудить с владельцем, прежде чем обрабатывать
  // дальше. reviewed НЕ выставляется (объявление остаётся непроверенным
  // по сути), но карточка прячется из очереди верификации, чтобы Светлана
  // могла двигаться дальше — см. MarketOffersReview.tsx, вкладка
  // "Обсуждение". Когда владелец жмёт "Вернуть на доработку", флаг
  // снимается (карточка снова попадает в обычную очередь), а комментарии
  // остаются — Светлана видит их в карточке редактирования при следующей
  // проверке. Оба текстовых поля очищаются при обычном сохранении формы
  // редактирования (updateMarketOffer) — вопрос считается закрытым.
  flaggedForDiscussion: boolean;
  discussionNote: string | null;
  ownerNote: string | null;
  // Не у всех объявлений заполнен — используется только как доп. сигнал
  // при поиске дублей (dedupKey), в остальном не критичен.
  floor: number | null;
  // Помещения с террасой — Kufar/Realt считают её площадь в общий size, а
  // терраса стоит заметно дешевле закрытого помещения, что занижает цену
  // за м² в сводке (см. netSize/netPricePerSqm ниже). Ни один источник не
  // помечает это в структурированных данных — ставится вручную на
  // /admin/market-offers, когда видно на плане/в описании.
  hasTerrace: boolean;
  terraceArea: number | null;
  address: string | null;
  adLink: string | null;
  updatedAt: string;
}

