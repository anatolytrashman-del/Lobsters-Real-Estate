-- Защита от дубля писем массовой рассылки (владелец, 2026-09-12: "это что,
-- письмо задублировалось?"). В этот день рассылку одновременно разбирали два
-- воркера — Edge Function по pg_cron и ручной запуск GitHub Actions, — и
-- 38 поставщиков получили по два одинаковых письма: ручной скрипт брал
-- список строк задания снапшотом в начале запуска и не перепроверял, не
-- взял ли их кто-то другой.
--
-- Код теперь захватывает строку задания атомарно (оба воркера), а эта
-- миграция добавляет последний рубеж на уровне базы: письмо переписки
-- помнит, по какой строке задания оно ушло, и вторая строка по тому же
-- заданию физически не вставится.
--
-- Колонка nullable, индекс частичный — старый код, который её не заполняет
-- (прод до публикации этой ветки, а также обычные письма из вкладки
-- "Письма" и входящие), продолжает работать без изменений.
alter table supplier_offer_emails
  add column if not exists bulk_job_item_id uuid;

create unique index if not exists supplier_offer_emails_bulk_job_item_uniq
  on supplier_offer_emails (bulk_job_item_id)
  where bulk_job_item_id is not null;

notify pgrst, 'reload schema';
